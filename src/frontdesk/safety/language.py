# Letters that only one of the three languages uses.
_SQ_LETTERS: Final = frozenset("ëç")
_IT_LETTERS: Final = frozenset("àèéìòù")
_NEUTRAL: Final = frozenset(
    {"ok", "okay", "si", "yes", "po", "no", "jo", "faleminderit", "grazie", "thanks", "mire"}
)


def detect_language(
    text: str, *, current: Language | None, supported: Sequence[Language], default: Language
) -> Language:
    fallback: Language = current if current is not None and current in supported else default
    words = tokens(text)
    if not words or (len(words) <= 2 and all(w in _NEUTRAL or w.isdigit() for w in words)):
        return fallback
    scores = {language: sum(1 for w in words if w in _MARKERS[language]) for language in supported}
    lowered = text.lower()
    if "sq" in scores and any(char in _SQ_LETTERS for char in lowered):
        scores["sq"] += 2
    if "it" in scores and any(char in _IT_LETTERS for char in lowered):
        scores["it"] += 1
    best = max(scores.values(), default=0)
    winners = [language for language, score in scores.items() if score == best]
    if best == 0 or len(winners) > 1:
        return fallback
    return winners[0]
